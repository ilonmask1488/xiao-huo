def build_stage(stage: int, units: list[dict], bosses: dict, base_files: list[str], out_dir: Path) -> None:
    """Общий сборщик ступени: слова, фразы, 3 урока на этап + диалог-босс."""
    from mnemonics import MNEMONICS

    hsk = load_hsk()
    dictionary = {w["hanzi"]: (w["id"], w["pinyin"]) for w in base_words(base_files)}
    known_ids = {w["id"] for w in base_words(base_files)}
    words_out, sentences_out, lessons_out, units_out, dialogues_out = [], [], [], [], []
    known: dict[str, str] = {}
    for f in [f"src/content/stage{i}/sentences.json" for i in range(1, stage)]:
        for s in json.loads((ROOT / f).read_text(encoding="utf-8")):
            known[plain_text(s)] = s["id"]
    ids = set(known_ids)

    for u in units:
        for wid, hanzi, py, ru_, pos in u["words"]:
            if hanzi in dictionary:
                raise SystemExit(f"Слово {hanzi} уже есть в курсе ({dictionary[hanzi][0]})")
            dictionary[hanzi] = (wid, py)

    for n, u in enumerate(units, start=1):
        uid = f"s{stage}-u{n}"
        unit_words = []
        for wid, hanzi, py, ru_, pos in u["words"]:
            if wid in ids:
                raise SystemExit(f"Повтор id {wid}")
            ids.add(wid)
            lv = hsk.get(hanzi, {})
            w = {"id": wid, "hanzi": hanzi, "pinyin": py, "ru": ru_, "pos": pos}
            if lv.get("old"):
                w["hsk2"] = lv["old"]
            if lv.get("new"):
                w["hsk3"] = lv["new"]
            tags = [f"stage{stage}"]
            if lv.get("old") != stage:
                tags.append("extra")
            # «Инженер» — профессиональные слова этапов модуля; общие слова HSK 1–2 из них не помечаем.
            if wid == "w-gongchengshi" or (u.get("engineering") and (lv.get("old") or 9) > 3):
                tags.append("engineering")
            w["tags"] = tags
            if wid in MNEMONICS:
                w["mnemonic"] = MNEMONICS[wid]
            w["reviewed"] = False
            words_out.append(w)
            unit_words.append(wid)

        sents = []
        for sid, text, ru_, literal in u["sentences"]:
            toks = tokenize(text, dictionary)
            s = {"id": sid, "tokens": toks, "ru": ru_, "unitId": uid, "reviewed": False}
            if literal:
                s["literal"] = literal
            sents.append(s)
        sentences_out += sents
        by_id = {s["id"]: s for s in sents}

        grammar = [{"title": t, "ru": r, "examples": ex} for t, r, ex in u["grammar"]]
        lessons = make_lessons(uid, u, unit_words, sents, grammar, by_id)

        # Финал этапа — диалог-«босс». Новые фразы диалога принадлежат этому этапу.
        for s in sentences_out:
            known[plain_text(s)] = s["id"]
        boss_n = [0]

        def new_sentence(text: str, unit_id: str, ru_: str, code=u["code"]) -> str:
            boss_n[0] += 1
            sid = f"s-{code}-b{boss_n[0]:02d}"
            s = {"id": sid, "tokens": tokenize(text, dictionary), "ru": ru_, "unitId": unit_id, "reviewed": False}
            sentences_out.append(s)
            sents.append(s)
            return sid

        boss = bosses[u["code"]]
        did = f"d-{uid}-boss"
        dialogues_out.append(make_dialogue(did, uid, boss["title"], boss["lines"], known, new_sentence))
        boss_lesson = {
            "id": f"{uid}-boss", "unitId": uid, "order": 4, "title": f"Обратный отсчёт: {boss['title']}", "newWords": [],
            "boss": {"passPercent": 80},
            "parts": [
                {"type": "explain", "title": boss["title"], "body": [boss["intro"], ru_boss_rule], "mascot": "celebrate"},
                {"type": "dialogue", "id": did},
            ],
        }
        lessons.append(boss_lesson)
        lessons_out += lessons
        units_out.append(
            {
                "id": uid, "stage": stage, "order": n, "code": u["code"], "title": u["title"], "situation": u["situation"],
                "goals": u["goals"], "lessons": [l["id"] for l in lessons], "newWords": unit_words,
                "sentences": [s["id"] for s in sents], "dialogues": [did], "grammarNotes": grammar, "boss": boss_lesson["id"],
            }
        )

    out_dir.mkdir(parents=True, exist_ok=True)
    for name, data in (
        ("units", units_out),
        ("words", words_out),
        ("sentences", sentences_out),
        ("lessons", lessons_out),
        ("dialogues", dialogues_out),
    ):
        (out_dir / f"{name}.json").write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    (ROOT / "src/content/characters.json").write_text(json.dumps(CHARACTERS, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(
        f"Ступень {stage}: этапов {len(units_out)}, уроков {len(lessons_out)}, слов {len(words_out)}, фраз {len(sentences_out)}, "
        f"диалогов {len(dialogues_out)}"
    )


ru_boss_rule = "Наберёшь 80% верных ответов — пуск! Не наберёшь — пуск перенесём, без штрафов."


def plain_text(s: dict) -> str:
    return "".join(t["hanzi"] for t in s["tokens"])


def split_body(text: str) -> list[str]:
    """Абзацы объяснения: по предложениям, не больше 2 абзацев."""
    parts = re.split(r"(?<=[.!?])\s+", text)
    if len(parts) <= 2:
        return parts
    mid = (len(parts) + 1) // 2
    return [" ".join(parts[:mid]), " ".join(parts[mid:])]


def make_lessons(uid: str, u: dict, words: list[str], sents: list[dict], grammar: list[dict], by_id: dict) -> list[dict]:
    half = (len(words) + 1) // 2
    a, b = words[:half], words[half:]
    assemblable = [s["id"] for s in sents if 2 <= words_of(s["tokens"]) <= 7]
    g1 = grammar[0]
    rest_g = grammar[1:]
    shown = set(g1["examples"]) | {e for g in rest_g for e in g["examples"]}
    others = [s["id"] for s in sents if s["id"] not in shown]

    def series(ws: list[str]) -> list[list[str]]:
        return [ws[i : i + 5] for i in range(0, len(ws), 5)]

    l1 = {
        "id": f"{uid}-l1", "unitId": uid, "order": 1, "title": f"{u['title']}: слова (1)", "newWords": a,
        "parts": [
            {"type": "explain", "title": "Новые слова", "mascot": "happy",
             "body": [f"Этап «{u['title']}». Послушай каждое слово: нажми на звук, выбери голос — носитель или синтез."],
             "words": a},
            {"type": "listen", "series": series(a)},
            {"type": "meaning", "prompt": "audio", "items": a},
            {"type": "repeat", "items": a[:3]},
            {"type": "read", "items": a[3:6]},
            {"type": "meaning", "prompt": "text", "items": list(reversed(a))},
        ],
    }
    l2_parts = [
        {"type": "explain", "title": "Ещё слова", "body": ["Вторая половина слов этапа."], "words": b},
        {"type": "listen", "series": series(b)},
        {"type": "meaning", "prompt": "audio", "items": b},
        {"type": "repeat", "items": b[:3]},
        {"type": "read", "items": b[3:6]},
        {"type": "explain", "title": g1["title"], "body": split_body(g1["ru"]), "sentences": g1["examples"], "mascot": "thinking"},
        {"type": "sentences", "items": g1["examples"]},
        {"type": "assemble", "items": [x for x in g1["examples"] if x in assemblable][:3]},
        {"type": "sayIt", "items": b[:4]},
    ]
    l2 = {"id": f"{uid}-l2", "unitId": uid, "order": 2, "title": f"{u['title']}: слова (2) и {g1['title']}", "newWords": b,
          "parts": [p for p in l2_parts if p.get("items", p.get("series", p.get("words", [1])))]}

    l3_parts: list[dict] = []
    for g in rest_g:
        l3_parts.append({"type": "explain", "title": g["title"], "body": split_body(g["ru"]), "sentences": g["examples"]})
        l3_parts.append({"type": "sentences", "items": g["examples"]})
    practice = others + [e for g in rest_g for e in g["examples"]]
    asm = [x for x in practice if x in assemblable]
    l3_parts += [
        {"type": "sentences", "items": others},
        {"type": "assemble", "items": asm[:4]},
        {"type": "repeat", "items": practice[:3]},
        {"type": "sayIt", "items": practice[3:6]},
        {"type": "meaning", "prompt": "text", "items": (a[:3] + b[:3])},
    ]
    l3 = {"id": f"{uid}-l3", "unitId": uid, "order": 3, "title": f"{u['title']}: фразы", "newWords": [],
          "parts": [p for p in l3_parts if p.get("items", [1])]}
    return [l1, l2, l3]


