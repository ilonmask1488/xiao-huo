def load_hsk() -> dict[str, dict]:
    if not HSK.exists():
        raise SystemExit("Нет scripts/.cache/hsk-complete.json — скачай complete.json из drkameleon/complete-hsk-vocabulary")
    data = json.loads(HSK.read_text(encoding="utf-8"))
    out: dict[str, dict] = {}
    for w in data:
        old = [int(l[4:]) for l in w["level"] if l.startswith("old-")]
        new = [int(l[4:].replace("+", "")) for l in w["level"] if l.startswith("new-")]
        out[w["simplified"]] = {"old": min(old) if old else None, "new": min(new) if new else None}
    return out


def tokenize(text: str, dictionary: dict[str, tuple[str, str]]) -> list[dict]:
    """Самое длинное совпадение по словарю; «|» — граница; [汉字:pin1 yin1] — токен не из словаря."""
    tokens: list[dict] = []
    for chunk in re.split(r"(\[[^\]]+\])", text):
        if not chunk:
            continue
        m = re.fullmatch(r"\[([^:\]]+):([^\]]+)\]", chunk)
        if m:
            tokens.append({"hanzi": m.group(1), "pinyin": m.group(2)})
            continue
        for seg in chunk.split("|"):
            i = 0
            while i < len(seg):
                ch = seg[i]
                if ch in PUNCT:
                    tokens.append({"hanzi": ch, "pinyin": ""})
                    i += 1
                    continue
                for L in range(min(5, len(seg) - i), 0, -1):
                    cand = seg[i : i + L]
                    if cand in dictionary:
                        wid, py = dictionary[cand]
                        # 这个 / 那个: счётное 个 в речи нейтральное (zhège)
                        if cand == "个" and tokens and tokens[-1]["hanzi"] in ("这", "那"):
                            py = "ge5"
                        tokens.append({"hanzi": cand, "pinyin": py, "wordId": wid})
                        i += L
                        break
                else:
                    raise SystemExit(f"Нет в словаре: «{seg[i]}» в «{text}» — добавь слово или разметку [..:..]")
    return tokens


def words_of(sentence_tokens: list[dict]) -> int:
    return sum(1 for t in sentence_tokens if t["pinyin"])


def base_words(files: list[str]) -> list[dict]:
    out: list[dict] = []
    for f in files:
        path = ROOT / f
        if path.exists():
            out += json.loads(path.read_text(encoding="utf-8"))
    return out


